def write_corpus(directory, docs):
    os.makedirs(directory, exist_ok=True)
    written = []
    for prefix in sorted({k.rsplit("_", 1)[0] for k in docs}):
        for i in range(1, 8 if directory == SAMPLE else 6):
            key = "%s_%02d" % (prefix, i)
            if key not in docs:
                continue
            text = "\n".join(docs[key]) + "\n"
            path = os.path.join(directory, key + ".txt")
            with open(path, "w", encoding="utf-8", newline="\n") as fh:
                fh.write(text)
            written.append((key + ".txt", docs[key][0], len(docs[key])))
    return written


