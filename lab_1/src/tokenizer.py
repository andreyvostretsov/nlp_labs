"""Токенизация русского текста.

Модуль реализован на стандартной библиотеке (только ``re``).

Контракт (INTERFACES.md, раздел 1):

* :func:`tokenize` — нижний регистр, извлечение слов (кириллица а-я + ё,
  латиница a-z) с допустимыми ВНУТРЕННИМИ дефисом и апострофом; цифры,
  пунктуация, эмодзи и пробелы отбрасываются;
* :func:`sent_tokenize` — разбиение на предложения по ``.``, ``!``, ``?``,
  ``…`` и по переводам строк.
"""

from __future__ import annotations

import re

__all__ = ["TOKEN_RE", "SENTENCE_BREAK_RE", "tokenize", "sent_tokenize"]


#: Слово: кириллица (``а-я`` плюс ``ё``) либо латиница (``a-z``).
#: Внутри слова допускаются дефис (``-``) и апостроф (``'`` в ASCII- и
#: типографском варианте ``’``), но только между буквами, поэтому ведущие и
#: замыкающие знаки в токен не попадают. Цифры в класс не входят и потому
#: отбрасываются. Регистрозависимости нет: ``re.IGNORECASE`` покрывает и
#: ``Ё``/``ё``. Дефис не склеивает кириллицу с латиницей, так как обе
#: альтернативы требуют одного алфавита по обе стороны от разделителя.
TOKEN_RE = re.compile(
    r"[а-яё]+(?:['’-][а-яё]+)*|[a-z]+(?:['’-][a-z]+)*",
    re.IGNORECASE,
)

#: Граница предложения: терминальный знак (``. ! ? …``), за которым следует
#: пробельный символ. Позиция нулевой ширины — сам знак остаётся в предложении.
SENTENCE_BREAK_RE = re.compile(r"(?<=[.!?…])(?=\s)")


def tokenize(text: str) -> list[str]:
    """Извлечь слова из текста.

    Возвращает список токенов в нижнем регистре. Допускаются внутренние
    дефис и апостроф. Цифры, пунктуация, эмодзи и пробелы отбрасываются.

    Args:
        text: исходный текст.

    Returns:
        Список токенов или ``[]`` для ``None``, пустой строки и строки,
        состоящей только из отбрасываемого «шума».
    """
    if not text:
        return []
    return [match.lower() for match in TOKEN_RE.findall(text)]


def sent_tokenize(text: str) -> list[str]:
    """Разбить текст на предложения.

    Границы предложений: знаки ``.``, ``!``, ``?``, ``…``, за которыми следует
    пробел, перевод строки или конец строки, а также сами переводы строк.

    Args:
        text: исходный текст.

    Returns:
        Список предложений без начальных и конечных пробелов; пустые
        предложения отбрасываются. Для ``None`` и пустой строки — ``[]``.
    """
    if not text:
        return []

    sentences: list[str] = []
    for line in text.split("\n"):
        for part in SENTENCE_BREAK_RE.split(line):
            sentence = part.strip()
            if sentence:
                sentences.append(sentence)
    return sentences
